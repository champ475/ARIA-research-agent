"""ui/settings.py — the Settings tab: your own LLM key, Telegram, the alert inbox
and signed-in devices. The operations are in services/settings.py."""

from __future__ import annotations

import html as _html
import logging

import gradio as gr

from services import settings as svc
from ui.theme import LOGOUT_JS, page_header, section_header
from utils.escaping import md_cell
from utils.helpers import IST as IST_TZ

log = logging.getLogger(__name__)


def sessions_md(rows: list[dict]) -> str:
    """Signed-in sessions table; the user agent is escaped (SEC-10)."""
    if not rows:
        return "_No active sessions._"
    lines = ["| Device | Last active (IST) |", "|---|---|"]
    for r in rows:
        ua = md_cell(r.get("user_agent") or "Unknown device", max_len=60)
        seen = (
            r["last_seen_at"].astimezone(IST_TZ).strftime("%d %b %Y, %H:%M") if r.get("last_seen_at") else "—"
        )
        lines.append(f"| {ua} | {seen} |")
    return "\n".join(lines)


def inbox_md(rows: list[dict]) -> str:
    """Render inbox rows. Alert text is generated by scripts/check_alerts.py
    from symbols/thresholds, but escape it anyway — it's shown as Markdown."""
    if not rows:
        return "*No alert notifications.*"
    lines = []
    for r in rows:
        when = r["created_at"].astimezone(IST_TZ).strftime("%d %b %H:%M IST") if r.get("created_at") else ""
        dot = "🔵 " if r.get("read_at") is None else ""
        lines.append(f"- {dot}**{when}** — {_html.escape(str(r['message']))}")
    return "\n".join(lines)


def build_settings_tab(user_state: gr.State):
    """
    Bring-your-own LLM key: works with any OpenAI-compatible provider
    (OpenAI, Groq, OpenRouter, Together, Fireworks, Ollama, ...). Without a
    key configured, every user gets a small free trial on the app's own
    Groq/Gemini keys (agents/graph_orchestrator.py's quota check).
    """
    gr.HTML(
        page_header("Settings", "Your model key, where alerts reach you, and the devices signed in to ARIA.")
    )

    gr.HTML(
        section_header(
            "Model and API key",
            "Bring your own key from any OpenAI-compatible provider for unlimited use. "
            "Without one, you get a free daily trial on ARIA's shared keys.",
        )
    )
    with gr.Column(elem_classes=["aria-panel"]):
        status = gr.Markdown("", elem_classes=["status-line"])
        with gr.Row():
            model_box = gr.Textbox(
                label="Model", placeholder="e.g. gpt-4o-mini, llama-3.3-70b-versatile", scale=2
            )
            base_url_box = gr.Textbox(
                label="Base URL (optional — leave blank for OpenAI itself)",
                placeholder="e.g. https://openrouter.ai/api/v1",
                scale=3,
            )
        api_key_box = gr.Textbox(label="API Key", type="password", placeholder="sk-...")

        with gr.Row(elem_classes=["toolbar"]):
            save_btn = gr.Button(
                "Save key", variant="primary", scale=0, elem_classes=["aria-ico", "ico-save"]
            )
            test_btn = gr.Button(
                "Test connection", variant="secondary", scale=0, elem_classes=["aria-ico", "ico-plug"]
            )
            clear_btn = gr.Button(
                "Remove my key", variant="stop", scale=0, elem_classes=["aria-ico", "ico-trash"]
            )

    def _refresh_status(user_id):
        if not user_id:
            return ""
        return svc.llm_status_md(user_id)

    def _save(user_id, model, base_url, api_key):
        if not user_id:
            return "", model, base_url, api_key
        try:
            model, base_url = svc.save_llm_key(user_id, model, base_url, api_key)
        except svc.KeyNotSaved as e:
            return e.message, e.model, e.base_url, e.api_key
        # clear the key field, never echo it back
        return svc.llm_status_md(user_id), model, base_url, ""

    def _test(user_id, model, base_url, api_key):
        if not user_id:
            return ""
        return svc.check_llm_key(user_id, model, base_url, api_key)

    def _clear(user_id):
        if not user_id:
            return "", "", "", ""
        svc.clear_llm_key(user_id)
        return svc.llm_status_md(user_id), "", "", ""

    save_btn.click(
        _save,
        inputs=[user_state, model_box, base_url_box, api_key_box],
        outputs=[status, model_box, base_url_box, api_key_box],
    )
    test_btn.click(_test, inputs=[user_state, model_box, base_url_box, api_key_box], outputs=[status])
    clear_btn.click(_clear, inputs=[user_state], outputs=[status, model_box, base_url_box, api_key_box])
    user_state.change(_refresh_status, inputs=[user_state], outputs=[status], show_progress="hidden")

    gr.HTML(
        section_header(
            "Telegram alerts", "Connect your own Telegram chat so the alerts you create come straight to you."
        )
    )
    with gr.Column(elem_classes=["aria-panel"]):
        tg_status = gr.Markdown("", elem_classes=["status-line"])
        with gr.Row(elem_classes=["toolbar"]):
            tg_connect_btn = gr.Button(
                "Connect Telegram", variant="primary", scale=0, elem_classes=["aria-ico", "ico-link"]
            )
            tg_disconnect_btn = gr.Button("Disconnect", variant="secondary", scale=0)

    def _tg_refresh(user_id):
        return svc.telegram_status_md(user_id) if user_id else ""

    def _tg_connect(user_id):
        return svc.telegram_connect_md(user_id) if user_id else ""

    def _tg_disconnect(user_id):
        if not user_id:
            return ""
        svc.telegram_disconnect(user_id)
        return svc.telegram_status_md(user_id)

    tg_connect_btn.click(_tg_connect, inputs=[user_state], outputs=[tg_status])
    tg_disconnect_btn.click(_tg_disconnect, inputs=[user_state], outputs=[tg_status])
    user_state.change(_tg_refresh, inputs=[user_state], outputs=[tg_status], show_progress="hidden")

    # ── Alert inbox (DATA-08) ────────────────────────────────────────────────
    # Fallback delivery channel: alerts that fired while Telegram wasn't linked
    # (or kept failing) land here instead of being silently dropped.
    gr.HTML(section_header("Alert inbox", "Alerts that couldn't be sent to Telegram are kept here."))
    with gr.Column(elem_classes=["aria-panel"]):
        inbox_view = gr.Markdown("")
        with gr.Row(elem_classes=["toolbar"]):
            inbox_refresh_btn = gr.Button(
                "Refresh", variant="secondary", scale=0, elem_classes=["aria-ico", "ico-refresh"]
            )
            inbox_read_btn = gr.Button(
                "Mark all read", variant="secondary", scale=0, elem_classes=["aria-ico", "ico-check"]
            )

    def _inbox_refresh(user_id, notify: bool = False):
        if not user_id:
            return ""
        try:
            rows = svc.inbox(user_id)
        except Exception as e:
            log.warning(f"[Settings] inbox load failed: {e}")
            return "⚠️ Couldn't load your alert inbox right now."
        unread = sum(1 for r in rows if r["read_at"] is None)
        if notify and unread:
            gr.Info(f"📥 You have {unread} unread alert notification(s) — see Settings → Alert inbox.")
        return inbox_md(rows)

    def _inbox_mark_read(user_id):
        if not user_id:
            return ""
        svc.inbox_mark_read(user_id)
        return _inbox_refresh(user_id)

    inbox_refresh_btn.click(_inbox_refresh, inputs=[user_state], outputs=[inbox_view])
    inbox_read_btn.click(_inbox_mark_read, inputs=[user_state], outputs=[inbox_view])
    user_state.change(
        lambda uid: _inbox_refresh(uid, notify=True),
        inputs=[user_state],
        outputs=[inbox_view],
        show_progress="hidden",
    )

    # ── Account security (SEC-04) ─────────────────────────────────────────────
    gr.HTML(section_header("Devices and your data"))
    with gr.Column(elem_classes=["aria-panel"]):
        sessions_view = gr.Markdown("")
        with gr.Row(elem_classes=["toolbar"]):
            logout_others_btn = gr.Button("Log out other devices", variant="secondary", scale=0)
            logout_here_btn = gr.Button(
                "Log out", variant="secondary", scale=0, elem_classes=["aria-ico", "ico-logout"]
            )
        gr.Markdown(
            "**Your data:** [download everything ARIA stores about you](/account/export) (JSON).  \n"
            "**Delete account:** permanently remove your account and all its data: "
            "[delete my account…](/account/delete)"
        )

    def _sessions(user_id):
        if not user_id:
            return ""
        try:
            rows = svc.devices(user_id)
        except Exception as e:
            log.warning(f"[Settings] session list failed: {e}")
            return "⚠️ Couldn't load your signed-in devices right now."
        return sessions_md(rows)

    def _logout_others(user_id, request: gr.Request):
        if not user_id:
            return ""
        from web.session import COOKIE_NAME

        n = svc.logout_other_devices(user_id, request.cookies.get(COOKIE_NAME))
        return f"✅ Logged out {n} other session(s).\n\n" + _sessions(user_id)

    logout_others_btn.click(_logout_others, inputs=[user_state], outputs=[sessions_view])
    logout_here_btn.click(None, js=LOGOUT_JS)
    user_state.change(_sessions, inputs=[user_state], outputs=[sessions_view], show_progress="hidden")

    return status
